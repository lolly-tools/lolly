// The Content-Credential mark assembly. Split out of docs/build.ts's shotCredential:
// the FACTS come from DocsRenderContext.credential (filesystem/C2PA at build time, a
// shipped manifest at runtime); THIS owns every byte of the HTML so both hosts emit
// identical markup. The mark is the imprint glyph plus a closed card of details that
// hover, focus or a tap opens. See plan, M0b.

import { esc } from './esc.ts';
import { PROV_SEAL, localeNum, approxCount } from './markdown.ts';
import type { CredentialFacts, DocsRenderContext } from './context.ts';

export interface CredentialRenderOpts {
  /** The served file's name, e.g. "gallery.svg" or "mascots/koala.webp". Drives the
   *  file-extension "kind" fact and label and (when fromPresent) the basename file line. */
  file: string;
  /** The wrapper class (shot-cred--alt / --asset / --mascot / --mast / --figure / ''). */
  extraClass: string;
  /** Whether this credential was requested for a PAGE ASSET (opts present at the call
   *  site) rather than a bare screenshot. It drives the basename file line. */
  fromPresent: boolean;
}

/**
 * Render one Content-Credential line from its facts, or '' when there are none. Mirrors
 * docs/build.ts's shotCredential exactly. `ctx` supplies t / htmlLang / nextCredId /
 * docIcon; `facts` supplies everything read from the served bytes.
 */
export function renderCredential(
  facts: CredentialFacts | null,
  opts: CredentialRenderOpts,
  ctx: Pick<DocsRenderContext, 't' | 'htmlLang' | 'nextCredId' | 'docIcon'>,
): string {
  // No readable credential means no line, and NO id is minted. The byte-identical id
  // sequence must not advance on a miss, matching shotCredential's early return.
  if (!facts) return '';
  const { file, extraClass, fromPresent } = opts;
  const id = ctx.nextCredId();
  const t = (s: string) => ctx.t(s);
  const num = (v: number) => localeNum(v, ctx.htmlLang);

  const ext = (file.split('.').pop() ?? '').toUpperCase();
  // "vector SVG" earns its adjective; a raster says only what it is.
  const kind = ext === 'SVG' ? `${t('vector')} SVG` : ext;
  const day = facts.when?.slice(0, 10) ?? null;
  const src = facts.src;
  const def = facts.recipe;
  const anat = facts.anat;

  // The opened card reads top to bottom: who signed it and when, what the file is, the AI
  // disclosure, then the actions. Facts are plain text in a row; the stylesheet puts a
  // middot between them (CSS content, so a screen reader does not read the dots out).
  const fact = (s: string) => `<span class="shot-cred-fact">${esc(s)}</span>`;
  const row = (cls: string, inner: string) => `<span class="shot-cred-row ${cls}"><span class="shot-cred-facts">${inner}</span></span>`;

  // (a) Who and when. A real space, not a margin, parts the seal from "signed by": the fact
  // takes its direction from its own text, and a space sits between them either way round.
  const who: string[] = [];
  if (facts.signer) {
    who.push(`<span class="shot-cred-fact shot-cred-sig">${PROV_SEAL} ${esc(t('signed by'))} `
      + `<span class="shot-cred-name">${esc(facts.signer)}</span></span>`);
  }
  if (day) who.push(`<time class="shot-cred-fact" datetime="${esc(day)}">${esc(day)}</time>`);

  // (b) What the file is. A page ASSET shows the served FILE (basename only) on its own
  // line; a screenshot does not. The anatomy group renders only when there is something
  // to say, and a zero count never renders: "0 paths" would unmake the vector claim.
  const anatFacts: string[] = [];
  if (anat?.kind === 'vector') {
    if (anat.paths > 0) anatFacts.push(fact(`${num(anat.paths)} ${t(anat.paths === 1 ? 'path' : 'paths')}`));
    if (anat.nodes > 0) anatFacts.push(fact(`${approxCount(anat.nodes, ctx.htmlLang)} ${t(anat.nodes === 1 ? 'node' : 'nodes')}`));
    if (anat.groups > 0) anatFacts.push(fact(`${num(anat.groups)} ${t(anat.groups === 1 ? 'group' : 'groups')}`));
    if (anat.paths === 0 && anat.groups === 0) {
      anatFacts.push(fact(`${num(anat.elements)} ${t(anat.elements === 1 ? 'element' : 'elements')}`));
    }
    if (anat.images > 0) anatFacts.push(fact(`${num(anat.images)} ${t(anat.images === 1 ? 'image' : 'images')}`));
  } else if (anat) {
    anatFacts.push(fact(t('pixels, not shapes')));
  }
  if (anat) anatFacts.push(fact(`${num(Math.round(anat.bytes / 1024))} KB`));
  const what = (kind ? fact(kind) : '')
    + (anatFacts.length ? `<span class="shot-cred-anat">${anatFacts.join('')}</span>` : '');

  // (c) The AI disclosure: a filled chip, then the model's name.
  const ai = (facts.ai ? `<span class="shot-cred-chip">${esc(t(facts.ai === 'generated' ? 'AI generated' : 'AI edited'))}</span>` : '')
    + (facts.model ? `<span class="shot-cred-model">${esc(t('generated by'))} <span class="shot-cred-name">${esc(facts.model)}</span></span>` : '');

  // The accessible label carries every fact, including the ones the compact card leaves out.
  const shotAt = def?.width && def.height
    ? `${num(def.width)} × ${num(def.height)}${def.dpi ? ` @ ${num(def.dpi)} dpi` : ''}` : '';
  const structure = anat?.kind === 'vector'
    ? `${num(anat.elements)} ${t(anat.elements === 1 ? 'element' : 'elements')}` : '';
  const how = anat?.kind === 'vector' && def
    ? t(def.walker ? 'captured with the HTML walker' : 'captured with the print path') : '';
  const label = [facts.ai ? t(facts.ai === 'generated' ? 'AI generated' : 'AI edited') : '', t('Content Credentials'),
    facts.signer ? `${t('signed by')} ${facts.signer}` : '', kind, facts.dimensions, day, facts.generator,
    facts.model ? `${t('generated by')} ${facts.model}` : '', facts.oversight ?? '',
    structure, shotAt, how].filter(Boolean).join(' - ');

  // "Copy signed source": offered only where the served file is pasteable source text.
  const copy = facts.canCopySource
    ? `<button type="button" class="shot-cred-do shot-cred-copy" data-copy-src="${esc(src)}"`
      + ` data-copied="${esc(t('Copied'))}" data-copy-failed="${esc(t('Copy failed'))}">`
      + `<span class="shot-cred-copy-label" aria-live="polite">${esc(t('Copy signed source'))}</span></button>`
    : '';
  // Every mark rests CLOSED: only the glyph shows until hover, focus or a tap opens the card.
  return `<span class="shot-cred${facts.ai ? ' shot-cred--ai' : ''}${extraClass ? ` ${extraClass}` : ''}">`
    + `<button type="button" class="shot-cred-btn" aria-expanded="false" aria-controls="${id}" aria-label="${esc(label)}">`
    + `${ctx.docIcon('imprint')}</button>`
    + `<span class="shot-cred-line" id="${id}">`
    + (who.length ? row('shot-cred-who', who.join('')) : '')
    + (fromPresent ? `<span class="shot-cred-row shot-cred-file">${esc(file.split('/').pop() ?? file)}</span>` : '')
    + (what ? row('shot-cred-what', what) : '')
    + (ai ? `<span class="shot-cred-row shot-cred-ai">${ai}</span>` : '')
    + `<span class="shot-cred-row shot-cred-acts">`
    + `<a class="shot-cred-do" href="/#/verify?src=${encodeURIComponent(src)}">${esc(t('Check it yourself'))}</a>`
    + `<a class="shot-cred-do" href="${src}" download>${esc(t('Get the signed file'))}</a>`
    + copy
    + `</span></span></span>`;
}
