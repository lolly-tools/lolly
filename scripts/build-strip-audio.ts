/**
 * Tools ship data: compile the engine's audio metadata stripper (engine/src/strip-audio.ts)
 * into a portable hook region, so Strip Hidden Data runs the same byte surgery as the
 * engine without importing the engine. The output is not minified, so a reviewer can read the
 * code the tool runs. After a change: node scripts/build-strip-audio.ts, then
 * pnpm run sync:shared. `--check` fails when the region is out of date.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { build } from 'esbuild';

const result = await build({
  entryPoints: ['engine/src/strip-audio.ts'], bundle: true, write: false, format: 'iife', globalName: 'LollyStripAudio',
  platform: 'neutral', target: 'es2022', minify: false, legalComments: 'none', charset: 'utf8',
});
// A directive mid-file is a no-op expression, so the region drops the directive.
const body = result.outputFiles[0]!.text.trim().replace(/^"use strict";\n/, '');
const source = `// SPDX-License-Identifier: MPL-2.0\n// Generated by scripts/build-strip-audio.ts from engine/src/strip-audio.ts.\n// === lolly:shared strip-audio - canonical source; generated by scripts/build-strip-audio.ts ===\n${body}\n// === /lolly:shared strip-audio ===\n`;
const path = 'community/_shared/strip-audio.js';
if (process.argv.includes('--check')) {
  if ((await readFile(path, 'utf8').catch(() => '')) !== source) throw new Error('Run node scripts/build-strip-audio.ts and pnpm run sync:shared.');
} else await writeFile(path, source);
