/** Final static delivery pass, after signing. Never transforms decoded file bytes. */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync, copyFileSync, statSync, utimesSync, openSync, readSync, closeSync, rmSync } from 'node:fs';
import { relative, resolve, join, dirname, sep } from 'node:path';
import { pathToFileURL } from 'node:url';
import { gzipSync, brotliCompressSync, constants } from 'node:zlib';
import { cachePolicy, publicStaticDeliveryClass } from '../packages/core/src/delivery-v1.ts';
import { compileMountedModelDelivery, readReviewedModelJson, validateMountedModelFiles, type MountedModelFile } from './lib/mounted-model-delivery.ts';
const sha = (bytes: Uint8Array) => createHash('sha256').update(bytes).digest('hex');
/** Bound memory while hashing large binary assets and model weights. */
export function fileSha(path: string): string {
  const digest = createHash('sha256'), buffer = Buffer.allocUnsafe(64 * 1024);
  const fd = openSync(path, 'r');
  try {
    for (;;) {
      const length = readSync(fd, buffer, 0, buffer.length, null);
      if (!length) break;
      digest.update(buffer.subarray(0, length));
    }
    return digest.digest('hex');
  } finally { closeSync(fd); }
}
export function staticFiles(root: string): string[] {
  const files: string[] = [];
  for (const e of readdirSync(root, { withFileTypes: true })) {
    if (e.name.startsWith('.')) continue;
    const path = join(root, e.name);
    if (e.isSymbolicLink()) throw new Error('Static release cannot contain symlinks');
    if (e.isDirectory()) files.push(...staticFiles(path));
    else if (e.isFile() && !/\.(gz|br)$/.test(path)) files.push(path);
  }
  return files.sort();
}
/** Preserve already published hash families. Collisions fail, never overwrite. */
export function retainHashedRelease(root: string, previous: string): number {
  if (resolve(root) === resolve(previous)) throw new Error('Retention input must be a separate release');
  let kept = 0;
  for (const source of staticFiles(previous)) {
    const url = '/' + relative(previous, source).split(sep).join('/');
    if (publicStaticDeliveryClass(url) !== 'public-immutable') continue;
    const target = join(root, url.slice(1));
    if (existsSync(target)) {
      if (fileSha(target) !== fileSha(source)) throw new Error('Immutable release collision');
      continue;
    }
    mkdirSync(dirname(target), { recursive: true }); copyFileSync(source, target); kept++;
  }
  return kept;
}
/** Generated from the same contract as Work/MCP. These maps are public-host only. */
export function nginxDeliveryMaps(): string {
  const imm = cachePolicy('public-immutable'), mutable = cachePolicy('public-revalidate'), error = cachePolicy('person-private');
  const immutable = '(?:/_app/|/ort-hf/[^/]+/|/info/docs\\.[a-zA-Z0-9_-]{6,40}\\.(css|js)$|/tools/[a-zA-Z0-9-]+@[0-9a-f]{16}/|/models/.+@[0-9a-f]{16}/|/.*\\.[0-9a-f]{16}\\.[a-zA-Z0-9]{1,16}$)';
  const map = (name: string, field: 'cacheControl' | 'cdnCacheControl') => [
    `map "$status:$uri" $${name} {`,
    `    default "${error[field]}";`,
    `    "~^(200|206|304):/sw\\.js$" "${field === 'cacheControl' ? 'no-cache, s-maxage=0, no-transform' : 'no-store'}";`,
    `    "~^(200|206|304):${immutable}" "${imm[field]}";`,
    `    "~^[23][0-9]{2}:" "${mutable[field]}";`,
    '}',
  ].join('\n');
  return '# Generated by scripts/build-delivery.ts from core delivery-v1; public static hosts only.\n' + map('lolly_delivery_cache', 'cacheControl') + '\n' + map('lolly_delivery_cdn', 'cdnCacheControl') + '\n';
}
export function prepareStaticDelivery(root: string, opts: { previous?: string; compression?: boolean; mountedModels?: readonly MountedModelFile[] } = {}) {
  root = resolve(root);
  const models = validateMountedModelFiles(opts.mountedModels ?? []);
  const retained = opts.previous ? retainHashedRelease(root, resolve(opts.previous)) : 0;
  const validators: string[] = ['# Generated decoded/wire validators; not a public asset.', 'map "$uri:$sent_http_content_encoding" $lolly_delivery_etag {', '    default "";'];
  const conditions = new Map<string, string>();
  const matchers = { identity: new Map<string, string>(), gzip: new Map<string, string>() };
  const validated = new Map<string, string>();
  const aliases = (url: string) => {
    const paths = [url];
    if (url === '/index.html') paths.push('/');
    if (/^\/t\/[a-z0-9-]+\.html$/.test(url)) paths.push(url.slice(0, -5));
    if (url === '/info/index.html') paths.push('/docs');
    else if (/^\/info\/.+\.html$/.test(url)) paths.push('/docs/' + url.slice(6, -5));
    const views: Record<string, string[]> = {
      tools: ['/tools'], utilities: ['/utilities', '/u'], d: ['/d'],
      v: ['/v', '/verify', '/valid'], a: ['/a', '/assets', '/c'],
      p: ['/p'], start: ['/start'], lab: ['/lab'], batch: ['/batch', '/pro'],
      unpack: ['/unpack', '/pdf'], profile: ['/profile'],
    };
    const view = /^\/view\/([a-z]+)\.html$/.exec(url)?.[1];
    if (view) paths.push(...(views[view] ?? []));
    if (url === '/t/design.html') paths.push('/design');
    return paths;
  };
  const conditional = (url: string, hash: string, metadata: { size: number; mtimeMs: number }, coding: 'identity' | 'gzip' = 'identity') => {
    const native = `"${Math.floor(metadata.mtimeMs / 1000).toString(16)}-${metadata.size.toString(16)}"`;
    for (const path of aliases(url)) {
      for (const prefix of ['', 'W/']) {
        const key = `${path}:${prefix}"${hash}"`;
        if (conditions.has(key) && conditions.get(key) !== native) throw new Error('Ambiguous static validator');
        conditions.set(key, prefix + native);
        validated.set(`${path}:${prefix}${native}`, `"${hash}"`);
      }
      const escaped = path.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      matchers[coding].set(`~^${escaped}:(?:[^,]*,)*\\s*(?:W/)?"${hash}"\\s*(?:,|$)`, native);
    }
  };
  let compressed = 0;
  const files = staticFiles(root);
  const mountedPaths = new Set(models.map(model => model.url));
  for (const path of files) {
    if (mountedPaths.has('/' + relative(root, path).split(sep).join('/'))) throw new Error('Mounted model path collides with static release');
  }
  for (const path of files) {
    const url = '/' + relative(root, path).split(sep).join('/');
    if (!/^\/[A-Za-z0-9._@/+,[\]()-]+$/.test(url)) throw new Error('Unsupported static release path');
    const hash = fileSha(path);
    // Release archives normalize metadata. The serving map uses that same
    // epoch, while external validators remain exclusively content-derived.
    utimesSync(path, 0, 0);
    for (const alias of aliases(url)) validators.push(`    "${alias}:" '"${hash}"';`);
    conditional(url, hash, statSync(path));
    // Sidecars are derived products. Remove stale outputs even when a changed
    // identity file is now too small or compression is disabled.
    for (const extension of ['gz', 'br']) rmSync(`${path}.${extension}`, { force: true });
    if (opts.compression !== false && statSync(path).size > 1024 && /\.(js|mjs|css|html|json|svg|txt|md|xml|webmanifest|map|wasm)$/i.test(path)) {
      const bytes = readFileSync(path);
      for (const [extension, coding, wire] of [
        ['gz', 'gzip', gzipSync(bytes, { level: 9 })],
        ['br', 'br', brotliCompressSync(bytes, { params: { [constants.BROTLI_PARAM_QUALITY]: 9 } })],
      ] as const) {
        if (wire.length >= bytes.length) continue;
        writeFileSync(`${path}.${extension}`, wire);
        const stat = statSync(path); utimesSync(`${path}.${extension}`, stat.atime, stat.mtime);
        for (const alias of aliases(url)) validators.push(`    "${alias}:${coding}" '"${sha(wire)}"';`);
        // Stock Nginx serves gzip only. Brotli siblings belong to Caddy or
        // explicit module builds, and must not acquire native gzip validators.
        if (coding === 'gzip') conditional(url, sha(wire), statSync(`${path}.${extension}`), coding);
        compressed++;
      }
    }
  }
  // Independent model volumes are identity-only. Staging verifies exact bytes
  // and epoch-zero metadata before these reviewed validators may be served.
  for (const model of models) {
    validators.push(`    "${model.url}:" '"${model.sha256}"';`);
    conditional(model.url, model.sha256, { size: model.size, mtimeMs: 0 });
  }
  validators.push('}');
  // Translate only this URI's current full hash to the native static validator.
  // Unknown and historical metadata tags cannot accidentally match equal sizes.
  for (const coding of ['identity', 'gzip'] as const) {
    validators.push(`map "$uri:$http_if_none_match" $lolly_match_${coding} {`, '    default \'"lolly-unrecognized-validator"\';');
    for (const [key, value] of matchers[coding]) validators.push(`    ${JSON.stringify(key)} '${value}';`);
    validators.push('}');
  }
  validators.push('map $http_if_none_match $lolly_native_if_none_match {', '    default "$lolly_match_identity, $lolly_match_gzip";', '    "" "";', '    "*" "*";', '}');
  validators.push('map "$uri:$http_if_range" $lolly_native_if_range {', '    default \'"lolly-unrecognized-validator"\';', '    "~:$" "";');
  for (const [key, value] of conditions) {
    if (!key.includes(':W/')) validators.push(`    ${JSON.stringify(key)} '${value}';`);
  }
  validators.push('}', 'map "$uri:$upstream_http_etag" $lolly_validated_etag {', '    default "";');
  for (const [key, value] of validated) validators.push(`    ${JSON.stringify(key)} '${value}';`);
  validators.push('}', 'map $upstream_status $lolly_response_etag {', '    304 $lolly_validated_etag;', '    default $upstream_http_x_lolly_content_etag;', '}');
  // Full hashes extend URI keys beyond x86 Nginx's default cache-line bucket.
  // Size from the actual longest key, including room for hash element metadata.
  let longestKey = 0;
  for (const key of conditions.keys()) longestKey = Math.max(longestKey, Buffer.byteLength(key));
  const bucketSize = 2 ** Math.ceil(Math.log2(Math.max(128, longestKey + 64)));
  const maxSize = 2 ** Math.ceil(Math.log2(Math.max(2048, conditions.size)));
  validators.unshift(`map_hash_bucket_size ${bucketSize};`, `map_hash_max_size ${maxSize};`);
  writeFileSync(join(root, '.delivery-etags.conf'), validators.join('\n') + '\n');
  return { files: files.length, retained, compressed, mountedModels: models.length };
}
export function main(args = process.argv.slice(2)): void {
  if (args.includes('--maps')) { console.log(nginxDeliveryMaps()); return; }
  const opt = (name: string) => args.includes(name) ? args[args.indexOf(name) + 1] : undefined;
  const root = opt('--root'); if (!root) throw new Error('Usage: node scripts/build-delivery.ts --root dist [--previous retained-release] [--no-compression] [--models-manifest JSON --models-manifest-sha256 SHA256 --models-archive-inventory JSON --models-archive-sha256 SHA256]');
  const manifest = opt('--models-manifest'), archive = opt('--models-archive-inventory');
  if (!manifest && (archive || opt('--models-manifest-sha256') || opt('--models-archive-sha256'))) throw new Error('Mounted model inputs require a reviewed manifest');
  if (!archive && opt('--models-archive-sha256')) throw new Error('Archived model pin needs an inventory');
  const mountedModels = manifest ? compileMountedModelDelivery(
    readReviewedModelJson(manifest, opt('--models-manifest-sha256') ?? ''),
    archive ? readReviewedModelJson(archive, opt('--models-archive-sha256') ?? '') : undefined,
  ) : undefined;
  console.log(JSON.stringify(prepareStaticDelivery(root, { previous: opt('--previous'), compression: !args.includes('--no-compression'), mountedModels })));
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
