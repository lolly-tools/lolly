/** Generate the parser tables and target census in docs/parser-inventory.md from
 * security/parser-assurance.json plus the fuzz harness's real ALL_TARGETS list. The
 * parsers are grouped by each entry's `family`, one folded table per family, so the
 * page opens on a summary rather than on a 92-row wall. */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import {
  registeredFuzzTargets,
  type ParserAssuranceRegistry,
  type ParserInventoryDetails,
} from './check-parser-assurance.ts';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const docsPath = path.join(repoRoot, 'docs', 'parser-inventory.md');
const registryPath = path.join(repoRoot, 'security', 'parser-assurance.json');
const fuzzPath = path.join(repoRoot, 'tests', 'fuzz', 'targets.ts');
const regressionsPath = path.join(repoRoot, 'tests', 'fuzz', 'regressions');
const GENERATED_NOTICE = '<!-- The parser tables and fuzz-target census are generated by scripts/build-parser-inventory.ts. Edit security/parser-assurance.json. -->';

/** The order the families appear in. A family not listed here follows, in name order,
 *  and an entry with no family is shown under "Other" (validation refuses that). */
export const PARSER_FAMILY_ORDER = [
  'Images and colour',
  'PDF and SVG',
  'Documents, interchange and design systems',
  'Text and fonts',
  'Audio, video and animation',
  'Provenance, watermarks and checks',
  'Emoji',
  'Design documents, links and agent requests',
];
const TABLE_HEAD = [
  '| Module | Input source | Bounds enforced | Direct test file | Fuzz target | Notes |',
  '|---|---|---|---|---|---|',
];

function tableCell(value: string): string {
  return value.replaceAll('|', '\\|').replaceAll('\n', ' ').trim();
}

export function renderParserTable(registry: ParserAssuranceRegistry): string {
  const groups = new Map<string, string[]>();
  for (const [id, entry] of Object.entries(registry.parsers)) {
    const details = entry.details as ParserInventoryDetails | undefined;
    if (!details) throw new Error(`${id}: registry entry has no inventory details`);
    const cells = [
      `\`${id}\``,
      details.inputSource,
      details.bounds,
      details.directTests,
      details.fuzzCoverage,
      details.notes,
    ].map(tableCell);
    const family = entry.family?.trim() || 'Other';
    groups.set(family, [...(groups.get(family) ?? []), `| ${cells.join(' | ')} |`]);
  }
  const rank = (family: string): number => {
    const at = PARSER_FAMILY_ORDER.indexOf(family);
    return at < 0 ? PARSER_FAMILY_ORDER.length : at;
  };
  const families = [...groups.keys()].sort((a, b) => rank(a) - rank(b) || a.localeCompare(b));
  const entries = Object.values(registry.parsers);
  const fuzzed = entries.filter((entry) => entry.fuzzTargets?.length).length;
  const waived = entries.length - fuzzed;
  const count = `${entries.length} ${entries.length === 1 ? 'parser' : 'parsers'} in ${families.length} ${families.length === 1 ? 'family' : 'families'}`;
  const summary = fuzzed === entries.length
    ? `${count}. ${entries.length === 1 ? 'It reaches a fuzz target and needs no waiver' : 'Every one reaches a fuzz target, and none needs a waiver'}. Open a family to see its parsers.`
    : `${count}: ${fuzzed} ${fuzzed === 1 ? 'reaches' : 'reach'} a fuzz target and ${waived} ${waived === 1 ? 'carries' : 'carry'} an owned, expiring waiver. Open a family to see its parsers.`;
  const blocks = families.flatMap((family) => {
    const rows = groups.get(family)!;
    return [`::: details ${family} (${rows.length})`, ...TABLE_HEAD, ...rows, ':::', ''];
  });
  return ['## The parsers', '', GENERATED_NOTICE, '', summary, '', ...blocks].join('\n').trimEnd() + '\n';
}

export function renderTargetCensus(targets: string[], regressions?: number): string {
  const names = targets.map((target) => `\`${target}\``);
  const listed = names.length > 1
    ? `${names.slice(0, -1).join(', ')} and ${names.at(-1)}`
    : (names[0] ?? 'none');
  const saved = regressions === undefined
    ? 'the saved regression inputs'
    : `the ${regressions} saved regression input${regressions === 1 ? '' : 's'}`;
  return `Fuzz coverage is the registered target list in \`tests/fuzz/targets.ts\` (\`ALL_TARGETS\`, at the end of the file). There ${targets.length === 1 ? 'is' : 'are'} ${targets.length}: ${listed}. \`tests/fuzz-regression.test.ts\` replays ${saved} in \`tests/fuzz/regressions/\` and runs a few hundred seeded mutations per target inside the normal \`pnpm test\` glob; \`node tests/fuzz/run.ts\` is the standalone soak.`;
}

/** The saved crash inputs the regression test replays, counted at build time. */
export function countRegressionInputs(dir = regressionsPath): number {
  return readdirSync(dir).filter((name) => name.endsWith('.bin')).length;
}

export function generateParserInventory(
  current: string,
  registry: ParserAssuranceRegistry,
  targets: string[],
  regressions?: number,
): string {
  const censusStart = current.indexOf('Fuzz coverage is the registered target list');
  const censusEnd = current.indexOf('\n\n', censusStart);
  if (censusStart < 0 || censusEnd < 0) throw new Error('parser inventory has no replaceable fuzz census');
  let generated = `${current.slice(0, censusStart)}${renderTargetCensus(targets, regressions)}${current.slice(censusEnd)}`;
  const parserStart = generated.indexOf('## The parsers\n');
  const parserEnd = generated.indexOf('\n## ', parserStart + 1);
  if (parserStart < 0 || parserEnd < 0) throw new Error('parser inventory has no replaceable parser table');
  generated = `${generated.slice(0, parserStart)}${renderParserTable(registry)}\n${generated.slice(parserEnd + 1)}`;
  return generated.endsWith('\n') ? generated : `${generated}\n`;
}

function main(): void {
  const current = readFileSync(docsPath, 'utf8');
  const registry = JSON.parse(readFileSync(registryPath, 'utf8')) as ParserAssuranceRegistry;
  const targets = [...registeredFuzzTargets(readFileSync(fuzzPath, 'utf8'))];
  const generated = generateParserInventory(current, registry, targets, countRegressionInputs());
  if (process.argv.includes('--check')) {
    if (current !== generated) {
      throw new Error('docs/parser-inventory.md is stale; run pnpm run build:parser-inventory');
    }
    console.log(`Parser inventory is current (${Object.keys(registry.parsers).length} rows, ${targets.length} fuzz targets).`);
    return;
  }
  writeFileSync(docsPath, generated);
  console.log(`Wrote docs/parser-inventory.md (${Object.keys(registry.parsers).length} rows, ${targets.length} fuzz targets).`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
