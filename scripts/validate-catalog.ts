/**
 * Catalog validator.
 *
 * Run as: npm run validate:catalog
 *
 * Verifies every tool and asset against its JSON Schema, plus structural
 * invariants the schemas can't express on their own:
 *
 *   - No duplicate tool IDs across the catalog
 *   - No duplicate asset IDs
 *   - Every tool referenced in tools/index.json has a tool.json under tools/<id>/
 *   - tools/index.json entries match their manifest (no denormalisation drift)
 *   - tools/index.slim.json is the same catalog, same order, re-derivable from the
 *     full index - and still carries none of the weight it exists to leave behind
 *   - catalog/previews/ is SVG-first: every raster there is named in RASTER_PREVIEWS
 *     with a written reason, and every named entry is still a raster (both ways).
 *     "Raster" is decided on CONTENT, not on the extension - an .svg that is only a
 *     wrapper around one embedded bitmap counts as one
 *   - Preview byte budgets: 300 KB a tile, 150 KB a look, 8 MB the directory - with
 *     per-file ceilings in OVER_BUDGET_PREVIEWS for the few that fit in no format
 *   - No blank tiles: a card measured empty is an ERROR when the tool has a usable
 *     example look to have captured instead, and a WARNING (the preset backlog) when
 *     it has none. Reads catalog/previews/blank-report.json and refuses a stale one
 *   - Every asset format URL resolves to a file that exists on disk
 *   - Every asset checksum matches the file's actual SHA-256 on disk
 *   - Every asset `depth` label matches a re-sniff of the file's own header
 *     (and no unsniffable/non-raster format carries one)
 *   - Every `canvas.*Field` names a real sub-field id in the sibling `fields`
 *     array (an unknown canvas KEY is caught by the schema, which closes the
 *     set; a broken reference can only be caught here)
 *   - Default `bindToProfile` values reference real profile fields
 *   - `palette` references on color inputs point to real palette assets
 *   - `replacedBy` on deprecated assets points to a real, non-deprecated asset
 *   - Brand-overlay declarations (`extends`) are sound: base exists in
 *     community/, community tools never declare one, overlay keeps the base id
 *
 * Index and checksums are generated by `npm run build:catalog`. This validator
 * is the guard that fails CI if either was committed stale.
 *
 * Exit code: 0 on success, 1 on any failure. Designed to run in CI before
 * publishing the catalog.
 */

import { readFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
