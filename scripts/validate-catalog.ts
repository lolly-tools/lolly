// default export only knows draft-07 and throws on the unknown meta-schema).
import Ajv from 'ajv/dist/2020.js';
// Shared catalog-entry derivation - the single source of truth for how a manifest
// maps to a tools/index.json entry (including the `exportable` flag). Importing it
// here (rather than re-deriving) prevents the two scripts from drifting. The build
// script only writes the index when run directly, so this import has no side effect.
import { entryFromManifest, slimEntry } from './build-catalog-index.ts';
// Brand palette (pure data - no DOM/browser deps, safe to import in Node). Used
// below to assert no hex carries two conflicting CMYK ink values, since the PDF
// export's hex→CMYK lookup (buildCmykPaletteMap) is keyed on hex and would
// silently resolve such a clash by entry order.
import { PALETTE } from '../shells/web/src/palette.ts';
import { isThemableIconSvg, parseThemedAssetId, parseIconThemesDoc } from '../engine/src/icon-theme.ts';
// The head-vs-version asset rule and the reserved head slug (plans/97 section 6a). Imported
// rather than re-stated: if the validator's idea of "this is a version asset" drifts
// from the shells', it either passes a pack that cannot resolve or fails one that can.
import { isVersionAssetId, readVersionIndex, DESIGN_VERSION_LATEST } from '../engine/src/design-version.ts';
import { parseRateCard, isRateCardError } from '../engine/src/rate-card.ts';
import { LANGS } from '../engine/src/lang.ts';
// Shared-hook-region drift guard - the writer (npm run sync:shared) and this
// check share one parser (same import-without-side-effect pattern as
// entryFromManifest above), so "what sync writes" and "what CI accepts" can't
// drift apart.
import { verifySharedRegions } from './sync-shared-hooks.ts';
// The one bit-depth sniff (checksum-assets.ts writes `depth` with it; this
// re-sniffs and compares). Same import-without-side-effect pattern as above:
// that module only rewrites the index when run directly.
import { depthForFormat } from './checksum-assets.ts';
// The blank-preview probe's thresholds and report name (plans/155 Task 4.4). Imported for
// the same reason as everything else here: the gate below judges rows the probe wrote, so a
// threshold it re-stated would be a second definition free to drift from the one that
// measured. The probe's `sharp` import is lazy precisely so this stays a data-only import.
import { BLANK_INK_RATIO, BLANK_STDDEV, GROUNDS, PROBE_DIM, REPORT_FILE as BLANK_REPORT_FILE } from './check-blank-previews.ts';
// The frozen CLI verb list has exactly one home (shells/cli/src/args.ts); a tool id that
// collides with one is unreachable from the terminal. See section 1.1 of the GA contract.
import { RESERVED_SUBCOMMANDS } from '../shells/cli/src/args.ts';
// The frozen URL/export param set (engine's single source of truth). A top-level
// input whose id is one of these can never round-trip through a URL or the CLI:
// parseUrlState skips every reserved key, so the value silently won't apply. See
// the reserved-id guard below.
import { RESERVED } from '../engine/src/url-mode.ts';
// `canvas.*Field` → sub-field-id existence. The schema closes the canvas key SET;
// this closes the reference side, which no JSON Schema can (it has to look at a
// SIBLING array). Pure module so tests can drive it without running the script.
import { canvasFieldRefErrors } from './lib/canvas-refs.ts';

// Fields tools/index.json mirrors from each manifest - kept in sync with
// scripts/build-catalog-index.ts.
const INDEX_FIELDS = ['name', 'description', 'version', 'status', 'category'];

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const PROFILE_FIELDS = new Set([
  'firstname', 'lastname', 'email', 'phone', 'city', 'country', 'headshot',
]);

// ─── Load schemas ───────────────────────────────────────────────────────────

const toolSchema = readJson('schemas/tool.schema.json');
const assetSchema = readJson('schemas/asset.schema.json');
const tokensSchema = readJson('schemas/tokens.schema.json');
const rateCardSchema = readJson('schemas/ratecard.schema.json');

const ajv = new Ajv({ allErrors: true, strict: false });
const validateTool = ajv.compile<any>(toolSchema);
const validateAsset = ajv.compile<any>(assetSchema);
const validateTokens = ajv.compile<any>(tokensSchema);
const validateRateCard = ajv.compile<any>(rateCardSchema);

// ─── Collect everything ─────────────────────────────────────────────────────

const errors: string[] = [];
const warnings: string[] = [];

const toolsDir = join(ROOT, 'tools');
const assetsIndex = readJson('catalog/assets/index.json');
const toolsIndex = readJson('catalog/tools/index.json');

// Underscore-prefixed dirs are pack infrastructure (community/_shared, the
// canonical hook-helper corpus), not tools - use-profile.ts excludes them from
// the view, and this filter keeps a stale view from failing as "missing tool.json".
const toolDirs = readdirSync(toolsDir).filter(d =>
  !d.startsWith('_') && statSync(join(toolsDir, d)).isDirectory(),
);

// ─── Tool validation ────────────────────────────────────────────────────────

const seenToolIds = new Set<string>();
// Dynamic manifest/index/asset JSON is validated against its JSON Schema at
// runtime; typing it as `any` here keeps the validator faithful without
// re-declaring every schema shape in TypeScript.
const toolManifests = new Map<string, any>(); // id → manifest

for (const dir of toolDirs) {
  const manifestPath = `tools/${dir}/tool.json`;
  const manifest = readJsonOptional(manifestPath);
  if (!manifest) {
    errors.push(`[${dir}] missing tool.json`);
    continue;
  }

  if (manifest.id !== dir) {
    errors.push(`[${dir}] manifest id "${manifest.id}" doesn't match directory name`);
  }

  if (seenToolIds.has(manifest.id)) {
    errors.push(`[${dir}] duplicate tool id "${manifest.id}"`);
  }

  // A tool id may never be a CLI subcommand word (plans/73-cli-ga-contract.md section 1.1). The
  // verbs win the first positional, so `brands/acme/tools/run/` would ship, pass every
  // other check, appear in `lolly list`, and be unreachable by any spelling - with no
  // diagnostic. Post-GA the only fixes are renaming a tool id (a permanent-contract
  // violation) or changing verb dispatch (breaking), so the guard belongs here, now.
  if ((RESERVED_SUBCOMMANDS as readonly string[]).includes(manifest.id)) {
    errors.push(
      `[${dir}] tool id "${manifest.id}" is a reserved CLI subcommand word ` +
      `(${RESERVED_SUBCOMMANDS.join(', ')}) - \`lolly ${manifest.id}\` would run the verb, ` +
      `so the tool would be permanently unreachable. Rename the tool.`,
    );
  }
  seenToolIds.add(manifest.id);
  toolManifests.set(manifest.id, manifest);

  if (!validateTool(manifest)) {
    for (const err of validateTool.errors ?? []) {
      errors.push(`[${dir}] schema: ${err.instancePath || '/'} ${err.message}`);
    }
    continue;
  }

  // Required files present?
  if (!existsSync(join(ROOT, `tools/${dir}/template.html`))) {
    errors.push(`[${dir}] missing template.html`);
  }
  if (manifest.hooks && !existsSync(join(ROOT, `tools/${dir}/hooks.js`))) {
    errors.push(`[${dir}] manifest declares hooks but hooks.js is missing`);
  }

  // "New from template" files (tools/<id>/templates/<tid>.json) - the SOURCE OF TRUTH
  // for the chooser + the reserved ?template=<id> launcher. Shape gate: each file must
  // parse, carry a non-empty string `id` and `name`, a plain-object `values` seed, the
  // basename must equal `id` (so <tid>.json ↔ id stays a stable, addressable contract),
  // and ids must be unique within the dir. (Like example looks, this does NOT resolve
  // the values map's asset refs - that scope matches the historical example validator.)
  const templatesDir = join(ROOT, `tools/${dir}/templates`);
  if (existsSync(templatesDir)) {
    const seenTemplateIds = new Set<string>();
    for (const file of readdirSync(templatesDir).sort()) {
      if (!file.endsWith('.json')) continue;
      const rel = `tools/${dir}/templates/${file}`;
      let t: any;
      try { t = JSON.parse(readFileSync(join(templatesDir, file), 'utf8')); } catch (e) {
        errors.push(`[${dir}] template ${file}: invalid JSON (${(e as Error).message})`);
        continue;
      }
      if (typeof t.id !== 'string' || !t.id) { errors.push(`[${dir}] template ${file}: missing/empty "id"`); continue; }
      if (typeof t.name !== 'string' || !t.name) errors.push(`[${dir}] template ${file}: missing/empty "name"`);
      if (!t.values || typeof t.values !== 'object' || Array.isArray(t.values)) {
        errors.push(`[${dir}] template ${file}: "values" must be a plain object (the input-id → value seed)`);
      }
      const base = file.replace(/\.json$/, '');
      if (t.id !== base) errors.push(`[${dir}] template ${file}: id "${t.id}" must match the file basename "${base}" (${rel})`);
      if (seenTemplateIds.has(t.id)) errors.push(`[${dir}] template ${file}: duplicate template id "${t.id}"`);
      seenTemplateIds.add(t.id);
      // Presets (plans/142): optional curated variants inside the template - each a
      // values OVERLAY merged over the template's base `values` (preset wins). Shape
      // gate mirrors the template's own: non-empty string id + name, plain-object
      // values, unique ids within the template.
      if (t.presets !== undefined) {
        if (!Array.isArray(t.presets)) {
          errors.push(`[${dir}] template ${file}: "presets" must be an array of { id, name, values } overlays`);
        } else {
          const seenPresetIds = new Set<string>();
          for (const p of t.presets) {
            const pid = p && typeof p === 'object' && typeof p.id === 'string' ? p.id : '';
            if (!pid) { errors.push(`[${dir}] template ${file}: a preset is missing a non-empty string "id"`); continue; }
            if (typeof p.name !== 'string' || !p.name) errors.push(`[${dir}] template ${file}: preset "${pid}" missing/empty "name"`);
            if (!p.values || typeof p.values !== 'object' || Array.isArray(p.values)) {
              errors.push(`[${dir}] template ${file}: preset "${pid}" "values" must be a plain object (the overlay merged over the template base)`);
            }
            if (seenPresetIds.has(pid)) errors.push(`[${dir}] template ${file}: duplicate preset id "${pid}"`);
            seenPresetIds.add(pid);
          }
        }
      }
    }
  }

  // On-device utility conventions (privacy:'on-device'): the tool processes the
  // user's OWN content, so its output must never be watermarked or stamped with
  // provenance. An experimental tool force-watermarks its exports, which directly
  // contradicts that - so the two are mutually exclusive. (The no-metadata side is
  // enforced at runtime: the exportFile path embeds nothing, and the render path
  // skips provenance for on-device tools.)
  if (manifest.privacy === 'on-device' && manifest.status === 'experimental') {
    errors.push(`[${dir}] privacy:'on-device' tools must not be status:'experimental' (experimental force-watermarks exports, which must never happen to a user's own file)`);
  }

  // bindToProfile checks
  for (const input of manifest.inputs) {
    if (input.bindToProfile && !PROFILE_FIELDS.has(input.bindToProfile)) {
      warnings.push(`[${dir}] input "${input.id}" bindToProfile "${input.bindToProfile}" is not a known profile field`);
    }
  }

  // A top-level input id must not collide with a RESERVED url-mode/export param.
  // parseUrlState skips reserved keys before matching inputs, so such an input can
  // never be set via a URL or the CLI - its value silently won't apply. The one
  // sanctioned overlap is the export-dimension family {width,height,w,h,unit,dpi}:
  // those inputs deliberately pair with the reserved dimension system. Block/vector
  // sub-fields are namespaced (`<input>.<field>`), so only top-level ids are checked.
  const DIMENSIONAL_IDS = new Set(['width', 'height', 'w', 'h', 'unit', 'dpi']);
  for (const input of manifest.inputs) {
    if (RESERVED.has(input.id) && !DIMENSIONAL_IDS.has(input.id)) {
      errors.push(`[${dir}] input "${input.id}" collides with a reserved URL/export parameter - it can never be set via URL or CLI (parseUrlState skips reserved keys). Rename it; the id-break window is the time to. Sanctioned overlaps: ${[...DIMENSIONAL_IDS].join(', ')}.`);
    }
  }

  // Free-canvas field references. `canvas` itself is a CLOSED set in the schema
  // (additionalProperties:false), so a typo'd KEY is already an Ajv error above.
  // This is the half a JSON Schema cannot express: every `canvas.*Field` VALUE has
  // to name a real sub-field id in the sibling `fields` array, because nothing at
  // runtime notices when it doesn't - the overlay's write no-ops and the compact
  // blocks URL drops the undeclared field, so a mis-named control ships as one that
  // silently does nothing. An error, not a warning: the manifest is the contract.
  for (const msg of canvasFieldRefErrors(manifest)) {
    errors.push(`[${dir}] ${msg}`);
  }

  // composes: ids must be unique within the manifest (they key {{asset <id>}} +
  // the render memo, so a duplicate silently shadows the earlier one).
  if (Array.isArray(manifest.composes)) {
    const seen = new Set<string>();
    for (const c of manifest.composes) {
      if (c && typeof c.id === 'string') {
        if (seen.has(c.id)) errors.push(`[${dir}] duplicate composes id "${c.id}"`);
        seen.add(c.id);
      }
    }
    if (manifest.composes.length && !(manifest.capabilities ?? []).includes('compose')) {
      errors.push(`[${dir}] declares "composes" but is missing the "compose" capability`);
    }
  }
}

// composes must reference real tools - a typo'd child id would only 404 at render
// time (and silently collapse the embed slot), so catch it here.
for (const [id, manifest] of toolManifests) {
  for (const c of manifest.composes ?? []) {
    if (c?.tool && !toolManifests.has(c.tool)) {
      errors.push(`[${id}] composes references unknown tool "${c.tool}"`);
    }
  }
}

// Cross-check the tool index references real tools, and that each entry matches
// its manifest. The manifest is the source of truth; the index is generated.
const indexedIds = new Set<string>();
for (const entry of toolsIndex.tools) {
  indexedIds.add(entry.id);
  const manifest = toolManifests.get(entry.id);
  if (!manifest) {
    errors.push(`tools/index.json references unknown tool "${entry.id}"`);
    continue;
  }
  for (const field of INDEX_FIELDS) {
    if (entry[field] !== manifest[field]) {
      errors.push(`tools/index.json: "${entry.id}" ${field} "${entry[field]}" ≠ manifest "${manifest[field]}" - run \`npm run build:catalog\``);
    }
  }
  // Derived flags: reuse the shared derivation so the generator and validator
  // can't drift on what they mean. `exportable` mirrors isExportable();
  // `personalized` (bindToProfile present) gates profile-aware gallery previews - 
  // both are manifest-derived, so a forgotten `npm run build:catalog` after adding
  // bindToProfile would otherwise silently leave a tool un-personalized. (icon is
  // disk-derived and intentionally not checked here; `preview` IS checked below.)
  const derived: any = entryFromManifest(manifest);
  if (entry.exportable !== derived.exportable) {
    errors.push(`tools/index.json: "${entry.id}" exportable ${entry.exportable} ≠ derived ${derived.exportable} - run \`npm run build:catalog\``);
  }
  if (!!entry.personalized !== !!derived.personalized) {
    errors.push(`tools/index.json: "${entry.id}" personalized ${!!entry.personalized} ≠ derived ${!!derived.personalized} - run \`npm run build:catalog\``);
  }
  // Preview path is disk-derived: build-previews rasterises expensive-to-paint SVGs
  // (huge paths / thousands of dots) to .png, so entryFromManifest picks the extension
  // that actually exists on disk. A stale index - pointing at .svg when the committed
  // preview is .png - renders as a broken image in the gallery. Flag the drift, but
  // only when the derived path points at a file that exists: a fresh checkout with no
  // generated previews yet is fine (the gallery tolerates an absent preview), so we
  // don't force a regeneration there.
  if (
    entry.preview !== derived.preview &&
    typeof derived.preview === 'string' &&
    existsSync(join(ROOT, derived.preview.replace(/^\//, '')))
  ) {
    errors.push(`tools/index.json: "${entry.id}" preview ${entry.preview} ≠ derived ${derived.preview} - run \`npm run build:catalog\` (after \`npm run previews\`)`);
  }
  // "New from template" metadata. THE WHOLE-POINT INVARIANT: the synced index must carry
  // template METADATA ONLY - never the heavy `values` seed (that's fetched on demand). A
  // stray `values` key here would re-bloat every client's index, defeating the lazy-file
  // storage entirely.
  for (const tmpl of (entry.templates ?? []) as Array<Record<string, unknown>>) {
    if (tmpl && typeof tmpl === 'object' && 'values' in tmpl) {
      errors.push(`tools/index.json: "${entry.id}" template "${tmpl.id}" carries "values" - the index must be metadata-only (values live in tools/<id>/templates/<tid>.json); run \`npm run build:catalog\``);
    }
  }
  // Drift guard: entryFromManifest re-scans tools/<id>/templates/*.json, so a forgotten
  // build:catalog after adding/editing/removing a template file fails CI. Compare the
  // (deterministic) derived metadata against the committed index copy.
  if (JSON.stringify(entry.templates ?? null) !== JSON.stringify(derived.templates ?? null)) {
    errors.push(`tools/index.json: "${entry.id}" templates drifted from tools/${entry.id}/templates/*.json - run \`npm run build:catalog\``);
  }
}
// Every tool with a manifest must appear in the index.
for (const id of toolManifests.keys()) {
  if (!indexedIds.has(id)) {
    errors.push(`tools/index.json is missing tool "${id}" - run \`npm run build:catalog\``);
  }
}

// ─── Slim first-paint index (drift guard) ───────────────────────────────────
// tools/index.slim.json is what the gallery's FIRST PAINT reads on a cold visit
// (plans/155 Task 3.8) - the same tools in the same order, cut to the fields the grid
// draws with. It is derived from the full index by slimEntry(), so re-deriving here is
// the whole check: a slim file that disagrees with index.json means someone edited or
// regenerated one without the other, and the symptom would be a first paint showing a
// tool that no longer exists, a preview path that 404s, or an order the upgrade
// re-render then shuffles under the user.
//
// Absent = a checkout whose catalog predates this file: an ERROR, not a skip. Unlike
// catalog/previews/ (a best-effort build artifact the gallery tolerates missing), the
// slim index is generated by the same `npm run build:catalog` as index.json itself, so
// "not there" always means "not regenerated".
const slimIndex = readJsonOptional('catalog/tools/index.slim.json');
if (!slimIndex) {
  // readJsonOptional has already reported a parse failure; only an actually absent
  // file needs a message of its own.
  if (!existsSync(join(ROOT, 'catalog/tools/index.slim.json'))) {
    errors.push('tools/index.slim.json is missing - run `npm run build:catalog`');
  }
} else {
  const slimTools: any[] = Array.isArray(slimIndex.tools) ? slimIndex.tools : [];
  // Same watermark, so a slim file can never claim to describe a different catalog
  // than the full one it was cut from.
  if (slimIndex.version !== toolsIndex.version || slimIndex.generatedAt !== toolsIndex.generatedAt) {
    errors.push('tools/index.slim.json: version/generatedAt ≠ tools/index.json - run `npm run build:catalog`');
  }
  if (slimTools.length !== toolsIndex.tools.length) {
    errors.push(`tools/index.slim.json lists ${slimTools.length} tools, tools/index.json lists ${toolsIndex.tools.length} - run \`npm run build:catalog\``);
  }
  // ORDER is compared, not just membership: the index array's order is the gallery's
  // within-section layout, so a slim file in a different order would re-shuffle the
  // grid the moment the full index arrives.
  const fullById = new Map<string, any>(toolsIndex.tools.map((t: any) => [t.id, t]));
  slimTools.forEach((entry, i) => {
    const full = fullById.get(entry?.id);
    if (!full) {
      errors.push(`tools/index.slim.json: "${entry?.id}" is not in tools/index.json - run \`npm run build:catalog\``);
      return;
    }
    if (entry.preview !== full.preview) {
      errors.push(`tools/index.slim.json: "${entry.id}" preview ${entry.preview} ≠ tools/index.json ${full.preview} - run \`npm run build:catalog\``);
    }
    if (toolsIndex.tools[i]?.id !== entry.id) {
      errors.push(`tools/index.slim.json: "${entry.id}" is at position ${i}, tools/index.json has "${toolsIndex.tools[i]?.id}" there - the order IS the gallery's layout; run \`npm run build:catalog\``);
    }
    if (JSON.stringify(entry) !== JSON.stringify(slimEntry(full))) {
      errors.push(`tools/index.slim.json: "${entry.id}" drifted from its tools/index.json entry - run \`npm run build:catalog\``);
    }
    // THE WHOLE-POINT INVARIANT, the twin of the template-`values` guard above: the
    // slim index exists to keep 335 KB of locale blocks, 17 KB of template metadata
    // and 22 KB of example bodies OFF the first-paint path. A stray one here would
    // quietly hand that weight straight back.
    for (const heavy of ['i18n', 'templates', 'examples']) {
      if (entry[heavy] !== undefined) {
        errors.push(`tools/index.slim.json: "${entry.id}" carries "${heavy}" - the slim index must stay first-paint sized; run \`npm run build:catalog\``);
      }
    }
  });
  for (const t of toolsIndex.tools) {
    if (!slimTools.some(s => s?.id === t.id)) {
      errors.push(`tools/index.slim.json is missing tool "${t.id}" - run \`npm run build:catalog\``);
    }
  }
}

// ─── Pre-rendered look bundle (first-paint guard) ───────────────────────────
// The gallery's example carousel + featured hero are bundle-FIRST: renderFeaturedVariant
// (shells/web/src/lib/featured-render.ts) asks bundledLook() for a committed data-URI out
// of catalog/previews/bundle.json BEFORE it will touch the engine, and only falls through
// to a LIVE off-screen render when a look is missing from the bundle or its sig no longer
// matches. That fallback is SILENT - the tile still fills, just by mounting a runtime - so
// editing a look's values in a manifest can quietly put an engine render back on the
// first-paint path. This guards the invariant that a pre-rendered look stays pre-rendered.
//
// The sig is one contract across three files and all three must agree:
//   build-preview-bundle.ts  JSON.stringify(looks[i].values ?? {})   ← written here
//   featured-render.ts:135   JSON.stringify(values)                  ← compared on the client
//   this check                                                        ← keeps them honest
//
// Severity split mirrors the tolerance the preview-path check above already applies:
// a STALE sig is an error (a demonstrable manifest↔bundle drift, always fixable by
// regenerating), while an ABSENT look is only a warning - build-previews is best-effort
// by design ("a look that fails just isn't bundled, and the gallery live-renders it as
// before"), so a missing entry must not turn a documented graceful degrade into a red
// build. No bundle at all = a checkout that hasn't generated previews: skip entirely.
const previewBundle = readJsonOptional('catalog/previews/bundle.json');
if (previewBundle) {
  for (const [id, manifest] of toolManifests) {
    // Canonical source is `examples`; `featured.variants` is the pre-`examples` alias.
    // Order MUST match build-preview-bundle.ts's looksOf() so the `<id>:<i>` keys line up.
    const looks: any[] = manifest.examples ?? manifest.featured?.variants ?? [];
    looks.forEach((look: any, i: number) => {
      const entry = previewBundle[`${id}:${i}`];
      const sig = JSON.stringify(look?.values ?? {});
      if (!entry) {
        warnings.push(`[${id}] example look ${i} is absent from catalog/previews/bundle.json - the gallery will LIVE-RENDER it on first paint; run \`npm run previews\` then \`npm run build:catalog\``);
      } else if (entry.sig !== sig) {
        errors.push(`[${id}] example look ${i} bundle sig is stale - the gallery will silently fall back to a live render on first paint; run \`npm run previews\` then \`npm run build:catalog\``);
      }
    });
  }
}

// ─── Preview bytes: the raster allowlist + size gates ───────────────────────
// catalog/previews/ is SVG-FIRST (plans/155 WP-2): a tool tile and every example look is
// a vector screenshot from the shell's own DOM→SVG walker unless the walker cannot recover it.
// This is the doctrine tests/docs-shots-vector.test.ts already enforces for /info
// screenshots, and it is here for the same measured reason. That docs PNG allowlist was
// never a set of limits anyone had measured: twelve of its twenty entries were born
// `format=png` in the first screenshot commit and were never re-tested after the walker
// improved. When they finally were, they converted unchanged - Mesh Gradient went from a
// 708 KB PNG to a 6 KB SVG of real <radialGradient> stops. `format=png` carried no expiry,
// so a workaround quietly became a property of the file.
//
// So this fails in BOTH directions, and the second one is the whole point:
//   - a raster in catalog/previews/ that RASTER_PREVIEWS does not name → re-capture it as
//     SVG (most convert on the first try) or add it with the reason it can't be;
//   - a RASTER_PREVIEWS entry whose file is now SVG or gone → delete the entry, because a
//     reason has to die the moment it stops being true. Without this half the list rots
//     exactly the way `format=png` did: silently, by staying listed after it stopped
//     being right.
//
// EXTENSION IS NOT EVIDENCE. The first cut of this gate keyed on the filename, so an
// `.svg` was assumed vector - and a walker that meets a <canvas> or a photograph emits
// exactly one <image href="data:image/jpeg;base64,…"/> and calls it an SVG. 766,405 B of
// this catalog was bitmaps in SVG clothing: no reason, no budget class, and BIGGER than
// the WebP the gate would have demanded, because base64 costs a third on top. So a
// preview is classified by what is inside it (isRasterInSvgClothing below), and the
// allowlist covers both spellings.
//
// PROFILE SCOPE: like every other check in this file, this reads the ACTIVE profile's
// catalog VIEW (catalog/ → brands/<active>/catalog). CI cannot mount the private suse
// pack, so CI only ever sees lolly-start; the suse catalog's previews are covered by
// loldev's local run (`validate:catalog:all` across every mounted profile - plans/155
// Task 6.2 puts that on the ship path). Entries are keyed by FILE NAME rather than tool
// id for exactly that reason: a name is something a given brand pack either ships or
// does not, so one list can be true of every profile it is run against. That is also why
// the both-ways check turns on the BASE name (`filter.look6`), not the whole filename: a
// profile that has no preview for that base at all simply doesn't ship it (suse excludes
// street-map; lolly-start has no diagram-builder), while a profile that has the base in
// some OTHER form has genuinely retired the reason and must delete the entry.

/** `filter.look6.webp` → `filter.look6`; `filter.webp` → `filter`. */
function previewBase(file: string): string {
  return file.replace(/\.[^.]+$/, '');
}

/**
 * Whether the ACTIVE profile is supposed to have a preview by that name at all - i.e.
 * it ships that tool, and (for a look) that tool has an example at that index.
 *
 * This is what lets ONE name-keyed list be true of every profile without going blind:
 * a listed file that is simply not this brand pack's business is skipped, but a listed
 * file the profile SHOULD have and doesn't is a deletion, and a deletion has to fail or
 * the reason outlives the file. The look-count half matters as much as the tool half -
 * a tool that drops its sixth example leaves a `…look5.webp` behind, and that stale
 * file is exactly the kind of thing a name-keyed list quietly grandfathers.
 */
function previewShippable(name: string): boolean {
  const look = /^(.*)\.look(\d+)$/.exec(previewBase(name));
  const manifest = toolManifests.get(look ? look[1]! : previewBase(name));
  if (!manifest) return false;
  if (!look) return true;
  // Mirrors build-previews.ts's own derivation (`t.examples ?? t.featured?.variants`).
  const looks = manifest.examples ?? manifest.featured?.variants ?? [];
  return Number(look[2]) < looks.length;
}

/**
 * An `.svg` that is really a bitmap in a wrapper: the picture is one embedded raster
 * data-URI and there is nothing else in the file to draw.
 *
 * Measured across both brand packs 2026-08-26. The two populations do not overlap:
 *
 *   raster in svg clothing   60-98% embedded,   271-1,804 B of markup left  (17 files)
 *   a real card WITH a photo 51-87% embedded,  2,426-16,262 B of markup left (6 files)
 *
 * finish-preview's mockups sit at 75-87% embedded but keep 9.9-16.3 KB of frame, type
 * and shadow geometry; email-signature is 52% avatar and 2.4 KB of real card. Those are
 * vector previews that happen to contain a picture, and rasterising them would throw the
 * vector half away. darkroom/audiogram/3d/flythrough/booth-studio/filter's photo looks
 * keep 271-1,804 B - an <svg>, an <image>, sometimes a background <rect>. Both tests
 * have to agree, so neither a big photo inside a real drawing nor a tiny wrapper around
 * a small mark is miscalled.
 *
 * The C2PA manifest is stripped before measuring the remainder: it is provenance
 * metadata every preview carries, not something the file draws.
 */
function isRasterInSvgClothing(svg: string): boolean {
  let embedded = 0;
  for (const m of svg.matchAll(/data:image\/(?:png|jpe?g|webp|gif|avif)[^"')\s]*/gi)) embedded += m[0].length;
  if (!embedded || embedded / svg.length < 0.6) return false;
  const residual = svg
    .replace(/data:image\/(?:png|jpe?g|webp|gif|avif)[^"')\s]*/gi, '')
    .replace(/<metadata>[\s\S]*?<\/metadata>/g, '');
  return residual.length < 4096;
}

