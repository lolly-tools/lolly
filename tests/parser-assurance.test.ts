import assert from 'node:assert/strict';
import test from 'node:test';
import type { ParserAssuranceRegistry } from '../scripts/check-parser-assurance.ts';
import {
  parseParserInventory,
  registeredFuzzTargets,
  validateParserAssurance,
} from '../scripts/check-parser-assurance.ts';
import { generateParserInventory, renderParserTable } from '../scripts/build-parser-inventory.ts';

const fuzzSource = `
export const alphaTarget: FuzzTarget = { name: 'alpha', async seeds() { return []; }, async invoke() {} };
export const spareTarget: FuzzTarget = { name: 'spare', async seeds() { return []; }, async invoke() {} };
export const ALL_TARGETS: FuzzTarget[] = [alphaTarget, spareTarget];
`;
const inventoryMarkdown = `
Fuzz coverage is the registered target list in \`tests/fuzz/targets.ts\`.

## The parsers

| Module | Input source | Bounds enforced | Direct test file | Fuzz target | Notes |
|---|---|---|---|---|---|
| \`engine/src/a.ts\` | hostile | cap | test | \`alpha\` (direct) | covered |
| \`engine/src/b.ts\` (reader) | hostile \`A \\| B\` | cap | test | none | waived |

## Writers, not parsers
`;

function registry(): ParserAssuranceRegistry {
  return {
    version: 1,
    inventory: 'docs/parser-inventory.md',
    parsers: {
      'engine/src/a.ts': {
        family: 'Images and colour',
        fuzzTargets: ['alpha'],
        details: {
          inputSource: 'hostile',
          bounds: 'cap',
          directTests: 'test',
          fuzzCoverage: '`alpha` (direct)',
          notes: 'covered',
        },
      },
      'engine/src/b.ts (reader)': {
        family: 'Emoji',
        waiver: { owner: 'security', expires: '2099-01-01', reason: 'Direct mutation target is tracked for the next parser-hardening pass.' },
        details: {
          inputSource: 'hostile `A | B`',
          bounds: 'cap',
          directTests: 'test',
          fuzzCoverage: 'none',
          notes: 'waived',
        },
      },
    },
  };
}

test('inventory parser handles escaped table pipes and reads the actual target list', () => {
  const targets = registeredFuzzTargets(fuzzSource);
  assert.deepEqual([...targets], ['alpha', 'spare']);
  assert.deepEqual(parseParserInventory(inventoryMarkdown, targets), [
    {
      id: 'engine/src/a.ts',
      source: 'engine/src/a.ts',
      fuzzTargets: ['alpha'],
      details: { inputSource: 'hostile', bounds: 'cap', directTests: 'test', fuzzCoverage: '`alpha` (direct)', notes: 'covered' },
    },
    {
      id: 'engine/src/b.ts (reader)',
      source: 'engine/src/b.ts',
      fuzzTargets: [],
      details: { inputSource: 'hostile `A | B`', bounds: 'cap', directTests: 'test', fuzzCoverage: 'none', notes: 'waived' },
    },
  ]);
});

test('parser inventory table is generated from registry details and escapes cell pipes', () => {
  const table = renderParserTable(registry());
  assert.match(table, /generated by scripts\/build-parser-inventory\.ts/i);
  assert.match(table, /hostile `A \\| B`/);
  assert.match(table, /^::: details Images and colour \(1\)$/m);
  assert.match(table, /^::: details Emoji \(1\)$/m);
  assert.ok(table.indexOf('Images and colour') < table.indexOf('Emoji'), 'families follow PARSER_FAMILY_ORDER');
  assert.match(table, /2 parsers in 2 families: 1 reaches a fuzz target and 1 carries an owned, expiring waiver/);
  const generated = generateParserInventory(inventoryMarkdown, registry(), ['alpha', 'spare'], 3);
  assert.match(generated, /There are 2: `alpha` and `spare`/);
  assert.match(generated, /replays the 3 saved regression inputs/);
  assert.deepEqual(
    validateParserAssurance({ inventoryMarkdown: generated, fuzzSource, registry: registry(), now: new Date('2026-09-04') }),
    [],
  );
});

test('coverage drift, stale entries and expired or missing waivers fail closed', () => {
  assert.deepEqual(
    validateParserAssurance({ inventoryMarkdown, fuzzSource, registry: registry(), now: new Date('2026-09-04') }),
    [],
  );

  const broken = registry();
  broken.parsers['engine/src/a.ts'] = {
    family: 'Images and colour',
    details: { inputSource: 'hostile', bounds: 'cap', directTests: 'test', fuzzCoverage: '`alpha` (direct)', notes: 'covered' },
  };
  broken.parsers['engine/src/b.ts (reader)']!.waiver!.expires = '2026-01-01';
  broken.parsers['stale.ts'] = {
    fuzzTargets: ['spare'],
    details: { inputSource: 'hostile', bounds: 'cap', directTests: 'test', fuzzCoverage: '`spare`', notes: 'stale' },
  };
  const errors = validateParserAssurance({ inventoryMarkdown, fuzzSource, registry: broken, now: new Date('2026-09-04') });
  assert.match(errors.join('\n'), /fuzz mapping drift/);
  assert.match(errors.join('\n'), /expired/);
  assert.match(errors.join('\n'), /stale registry entry/);
});

test('the parser summary agrees in number for one and for many', () => {
  const one = registry();
  delete one.parsers['engine/src/b.ts (reader)'];
  assert.match(renderParserTable(one), /^1 parser in 1 family\. It reaches a fuzz target and needs no waiver\./m);
  assert.match(generateParserInventory(inventoryMarkdown, one, ['alpha'], 1), /There is 1: `alpha`/);

  const many = registry();
  for (const id of ['engine/src/c.ts', 'engine/src/d.ts']) {
    many.parsers[id] = { ...structuredClone(many.parsers['engine/src/b.ts (reader)']!), family: 'Emoji' };
  }
  many.parsers['engine/src/e.ts'] = structuredClone(many.parsers['engine/src/a.ts']!);
  assert.match(renderParserTable(many), /^5 parsers in 2 families: 2 reach a fuzz target and 3 carry an owned, expiring waiver\./m);
});
