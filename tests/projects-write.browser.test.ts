/** Exercise file creation and project saves through the real shell and IndexedDB. */
import test from 'node:test';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { createRequire } from 'node:module';
import { getBrowser, closeBrowser, browserInstalled } from '../packages/node-shell/src/browsers.ts';
import { shellSettled } from './helpers/shell-settled.ts';

const root = fileURLToPath(new URL('..', import.meta.url));
test('Projects creates Write files and Text saves the latest editor contents into a project', {
  skip: browserInstalled() ? false : 'No browser installed; set LOLLY_BROWSER_CHANNEL=chrome.', timeout: 240_000,
}, async () => {
  process.env.LOLLY_ROOT = root;
  process.env.LOLLY_PROFILE = 'lolly-start';
  const { createServer } = await import('vite');
  const require = createRequire(import.meta.url);
  const server = await createServer({ root: join(root, 'shells/web'), configFile: join(root, 'shells/web/vite.config.js'),
    cacheDir: join(root, 'node_modules/.vite-projects-write-test'), server: { host: '127.0.0.1', port: 0, fs: { allow: [root, dirname(require.resolve('harfbuzzjs'))] } }, logLevel: 'error' });
  await server.listen();
  const origin = server.resolvedUrls!.local[0]!;
  const browser = await getBrowser(), context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  const page = await context.newPage(), errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    await page.goto(`${origin}#/p`, { waitUntil: 'networkidle' });
    await shellSettled(page);
    await page.locator('.projects').waitFor();
    await page.locator('.projects').evaluate(el => el.dispatchEvent(new MouseEvent('contextmenu', { bubbles: true, clientX: 500, clientY: 250, button: 2 })));
    await page.locator('.projects-menu [data-act="new-file"]').click();
    const dialog = page.getByRole('dialog', { name: 'New file', exact: true });
    await dialog.locator('[data-file-name]').fill('Roadmap');
    await dialog.locator('[data-file-type]').selectOption('markdown');
    await dialog.getByRole('button', { name: 'Create file', exact: true }).click();
    await page.locator('.text-workspace h1').filter({ hasText: 'Write' }).waitFor();
    await page.getByText('Tool loaded', { exact: true }).waitFor();
    const slot = new URLSearchParams(page.url().split('?')[1]).get('slot')!;
    assert.ok(slot.startsWith('write:'));
    assert.equal(await page.locator('[data-write-name]').inputValue(), 'Roadmap.md');
    assert.equal(await page.locator('[data-document]').isVisible(), true);
    assert.equal(await page.locator('[data-mode="characters"]').isVisible(), false);
    const empty = await page.evaluate(async slot => {
      const path = '/src/lib/host-ref.ts';
      return (await import(path)).getHostRef().state.load(slot);
    }, slot);
    assert.equal(empty.body, '', 'the empty file is durable before editing');
    const text = '# Roadmap\n\nKeep **all** the words.\n\n[Unsafe](javascript:alert(1))';
    await page.locator('[data-editor] textarea').fill(text);
    const preview = page.locator('[data-write-preview]');
    await preview.locator('h1').filter({ hasText: 'Roadmap' }).waitFor();
    assert.equal(await preview.locator('h1').innerText(), 'Roadmap');
    assert.equal(await preview.locator('strong').innerText(), 'all');
    await page.locator('[data-write-format]').selectOption('plain');
    await page.locator('[data-editor] textarea').fill(text.replace('Roadmap', 'Plain file'));
    await preview.locator('h1').filter({ hasText: 'Plain file' }).waitFor();
    assert.equal(await preview.locator('strong').innerText(), 'all', 'Markdown preview also renders a plain text file');
    await page.locator('[data-write-format]').selectOption('markdown');
    await page.locator('[data-editor] textarea').fill(text);
    await preview.locator('h1').filter({ hasText: 'Roadmap' }).waitFor();
    assert.equal(await preview.locator('a[href^="javascript:"]').count(), 0);
    assert.equal(await page.getByRole('dialog', { name: 'Markdown preview', exact: true }).count(), 0);
    const editorBounds = await page.locator('[data-editor-pane]').boundingBox();
    const paneBounds = await page.locator('.write-pane').boundingBox();
    assert.ok(editorBounds && paneBounds && editorBounds.x + editorBounds.width <= paneBounds.x, 'preview sits beside the source');
    const splitter = page.getByRole('separator', { name: 'Resize writing panes' });
    const grip = (await splitter.boundingBox())!;
    await page.mouse.move(grip.x + grip.width / 2, grip.y + 60);
    await page.mouse.down();
    await page.mouse.move(grip.x + 120, grip.y + 60, { steps: 5 });
    await page.mouse.up();
    assert.ok((await page.locator('[data-editor-pane]').boundingBox())!.width > editorBounds.width + 80);
    await splitter.press('Enter');
    assert.ok(Math.abs((await page.locator('[data-editor-pane]').boundingBox())!.width - editorBounds.width) < 2);
    await page.locator('[data-write-hide]').click();
    assert.equal(await page.locator('.write-pane').isVisible(), false);
    const workspaceBounds = (await page.locator('.write-workspace').boundingBox())!;
    assert.ok((await page.locator('[data-editor-pane]').boundingBox())!.width > workspaceBounds.width - 80, 'hidden companion gives the editor the full workspace width');
    await page.locator('[data-write-measure]').selectOption('72');
    const narrowWidth = await page.locator('[data-editor] textarea').evaluate(el => el.clientWidth);
    assert.ok(narrowWidth < workspaceBounds.width - 100);
    await page.locator('[data-write-measure]').selectOption('nowrap');
    assert.equal(await page.locator('[data-editor] textarea').getAttribute('wrap'), 'off');
    await page.locator('[data-write-measure]').selectOption('custom');
    await page.locator('[data-write-columns]').fill('65');
    await page.locator('[data-write-columns]').press('Tab');
    assert.equal(await page.locator('.write-workspace').evaluate(el => (el as HTMLElement).style.getPropertyValue('--write-measure')), '65ch');
    await page.locator('[data-write-measure]').selectOption('full');
    await page.locator('[data-write-line-focus]').check();
    await page.locator('[data-editor] textarea').evaluate((el: HTMLTextAreaElement) => {
      el.focus(); el.setSelectionRange(0, 0); el.dispatchEvent(new Event('select'));
    });
    await page.waitForFunction(() => document.querySelector('[data-editor]')?.getAttribute('data-active-line') === '1');
    await page.locator('[data-editor] textarea').press('ArrowDown');
    await page.waitForFunction(() => document.querySelector('[data-editor]')?.getAttribute('data-active-line') === '2');
    assert.equal(await page.locator('.write-line-ink').isVisible(), true);
    assert.equal(await page.locator('[data-editor] textarea').inputValue(), text);
    await page.locator('[data-writer-view="preview"]').click();
    await page.locator('[data-write-fullscreen]').click();
    await page.locator('.write-distraction').waitFor();
    assert.equal(await page.locator('.text-document-toolbar').isVisible(), false);
    assert.equal(await page.locator('.write-pane').isVisible(), false);
    assert.ok((await page.locator('[data-editor] textarea').boundingBox())!.height > 700);
    await page.locator('[data-editor] textarea').press('Escape');
    await page.locator('.write-distraction').waitFor({ state: 'detached' });
    assert.equal(await page.locator('[data-editor] textarea').inputValue(), text);
    assert.equal(await page.locator('.write-pane').isVisible(), true, 'fullscreen exit restores the companion');
    await page.locator('[data-write-hide]').click();
    await page.locator('[data-write-line-focus]').uncheck();
    assert.equal(await page.locator('[data-writer-view="preview"]').getAttribute('aria-expanded'), 'false');
    await page.locator('[data-writer-view="preview"]').click();
    await page.locator('[data-editor] textarea').fill('# Live preview\n\nIn order to help, the report was quickly written.');
    await preview.locator('h1').filter({ hasText: 'Live preview' }).waitFor();
    await page.locator('[data-writer-view="checks"]').click();
    await page.locator('.write-issues').getByText('Possible passive voice', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Find suggestion 1 in text', exact: true }).click();
    assert.equal(await page.locator('[data-editor] textarea').evaluate((el: HTMLTextAreaElement) => el.value.slice(el.selectionStart, el.selectionEnd)), 'In order to');
    await page.getByRole('button', { name: 'Use “To”', exact: true }).click();
    assert.match(await page.locator('[data-editor] textarea').inputValue(), /To help/);
    await page.locator('[data-undo]').click();
    assert.match(await page.locator('[data-editor] textarea').inputValue(), /In order to help/);
    await page.locator('[data-editor] textarea').fill(text);
    await page.locator('[data-writer-tab="preview"]').click();
    await preview.locator('h1').filter({ hasText: 'Roadmap' }).waitFor();
    await page.locator('[data-save-project]').click();
    const save = page.locator('dialog.save-dialog');
    await save.waitFor();
    await save.locator('[data-act="save-project"]').click();
    await save.waitFor({ state: 'detached' });
    await page.reload({ waitUntil: 'networkidle' });
    await shellSettled(page);
    await page.locator('[data-editor] textarea').waitFor();
    assert.equal(await page.locator('[data-editor] textarea').inputValue(), text);
    assert.equal(await page.locator('[data-write-name]').inputValue(), 'Roadmap.md');
    // The independent Text utility must file its current editor buffer, including
    // a save made before its normal input debounce has elapsed.
    await page.goto(`${origin}#/tool/text-helper`, { waitUntil: 'networkidle' });
    await shellSettled(page);
    await page.getByText('Tool loaded', { exact: true }).waitFor();
    await page.locator('[data-mode="text"]').click();
    await page.locator('[data-editor] textarea').fill('The final keystrokes stay with this project.');
    await page.locator('[data-save-project]').click();
    await save.waitFor();
    await save.locator('[data-project]').selectOption('__new_project__');
    await save.locator('[data-new-project]').fill('Writing');
    await save.locator('[data-act="save-project"]').click();
    await save.waitFor({ state: 'detached' });
    const kept = await page.evaluate(async () => {
      const path = '/src/lib/host-ref.ts';
      const host = (await import(path)).getHostRef();
      const profile = await host.profile.get();
      const folder = profile.folders.find((entry: { name: string }) => entry.name === 'Writing');
      const document = await host.state.load(folder.items[0].ref);
      return { folder, document };
    });
    assert.equal(kept.document.__toolId, 'text-helper');
    assert.equal(kept.document.body, 'The final keystrokes stay with this project.');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(`${origin}#/tool/write?slot=${encodeURIComponent(slot)}`, { waitUntil: 'networkidle' });
    await shellSettled(page);
    await page.locator('[data-write-name]').waitFor();
    await page.locator('[data-writer-view="checks"]').click();
    await page.locator('.write-pane').waitFor({ state: 'visible' });
    const phoneEditor = await page.locator('[data-editor-pane]').boundingBox();
    const phonePane = await page.locator('.write-pane').boundingBox();
    assert.ok(phoneEditor && phonePane && phoneEditor.y + phoneEditor.height <= phonePane.y, 'phone panes stack without covering the editor');
    await page.locator('[data-writer-tab="checks"]').press('Escape');
    assert.equal(await page.locator('.write-pane').isVisible(), false);
    assert.equal(await page.locator('[data-editor] textarea').evaluate(el => el === document.activeElement), true);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Write fits on a phone');
    assert.deepEqual(errors, []);
  } catch (error) {
    console.error(JSON.stringify({ errors, text: (await page.locator('body').innerText()).slice(-4000) }));
    throw error;
  } finally {
    await context.close(); await closeBrowser(); await server.close();
  }
});
