function barrelNames(): string[] {
  const src = readFileSync(new URL('../engine/src/index.ts', import.meta.url), 'utf8');
  const names = new Set<string>();
  for (const line of src.split('\n')) {
    const group = line.match(/^export\s*(type\s*)?\{([^}]*)\}\s*from/);
    if (group) for (const raw of group[2]!.split(',')) { const entry = raw.trim().replace(/^type\s+/, ''); if (entry) names.add(entry.split(/\s+as\s+/).pop()!.trim()); }
    const local = line.match(/^export\s+(?:const|function|class|type|interface)\s+(\w+)/);
    if (local) names.add(local[1]!);
  }
  return [...names].sort();
}

test('the engine barrel exports exactly the pinned names', () => {
  const actual = barrelNames();
  const missing = EXPECTED.filter((n) => !actual.includes(n));
  const extra = actual.filter((n) => !EXPECTED.includes(n));
  assert.deepEqual({ missing, extra }, { missing: [], extra: [] },
    'engine/src/index.ts changed: update EXPECTED in tests/engine-barrel.test.ts in the same commit (an export added by accident is the case this catches)');
});
