import assert from 'node:assert/strict';
import test from 'node:test';
import {
  type AdvisoryException,
  type DependencyRoot,
  advisoryExceptionProblems,
  auditCounts,
  cargoAuditArgs,
  compareVersions,
  discoverAuthoritativeLocks,
  loadInventory,
  parseCargoLock,
  parseInventory,
  validateAdvisoryExceptions,
  validateCoverage,
} from '../scripts/audit-all.ts';

const ZIP_ADVISORIES = ['RUSTSEC-2026-0367', 'RUSTSEC-2026-0368', 'RUSTSEC-2026-0369'];

const zipException: AdvisoryException = {
  advisories: ZIP_ADVISORIES,
  crate: 'zip',
  fixedIn: '9.0.0',
  via: 'tauri-plugin-updater',
  viaFixedIn: '2.14.1',
  approvedBy: 'test',
  justification: 'test fixture',
  tracking: ['https://example.invalid/upstream'],
};

const desktopRoot: DependencyRoot = {
  id: 'desktop-cargo',
  ecosystem: 'cargo',
  directory: 'shells/tauri-desktop/src-tauri',
  lockfile: 'shells/tauri-desktop/src-tauri/Cargo.lock',
  exposure: 'shipped-runtime',
  owner: 'shells/tauri-desktop',
  advisoryExceptions: [zipException],
};

/** A Cargo.lock in the format Cargo writes, from [name, version, dependencies] rows. */
function lock(...packages: Array<[string, string, string[]?]>): string {
  const lines = ['# This file is automatically @generated by Cargo.', '# It is not intended for manual editing.', 'version = 4', ''];
  for (const [name, version, deps = []] of packages) {
    lines.push('[[package]]', `name = "${name}"`, `version = "${version}"`);
    lines.push('source = "registry+https://github.com/rust-lang/crates.io-index"');
    if (deps.length) lines.push('dependencies = [', ...deps.map((dep) => ` "${dep}",`), ']');
    lines.push('');
  }
  return lines.join('\n');
}

const app = (...deps: string[]): [string, string, string[]] => ['lolly-desktop', '1.1.1', ['tauri-plugin-updater', ...deps]];
const heldLock = lock(app(), ['tauri-plugin-updater', '2.13.2', ['tar', 'zip']], ['tar', '0.4.46'], ['zip', '4.6.1', ['crc32fast']], ['crc32fast', '1.5.0']);

test('every authoritative npm/Cargo lock has an audit owner', () => {
  const inventory = loadInventory();
  assert.doesNotThrow(() => validateCoverage(inventory));
  assert.deepEqual(discoverAuthoritativeLocks(), [
    'packages/node-shell/wasm/adobe-psd/Cargo.lock',
    'packages/node-shell/wasm/geometry-kernel/Cargo.lock',
    'packages/node-shell/wasm/layout-kernel/Cargo.lock',
    'packages/node-shell/wasm/pixel-kernel/Cargo.lock',
    'packages/node-shell/wasm/portable-math/Cargo.lock',
    'packages/node-shell/wasm/skera/Cargo.lock',
    'pnpm-lock.yaml',
    'shells/tauri-desktop/pnpm-lock.yaml',
    'shells/tauri-desktop/src-tauri/Cargo.lock',
    'shells/tauri-desktop/src-tauri/probes/glib-iterator/Cargo.lock',
    'shells/tauri-desktop/src-tauri/probes/isolated-capture/Cargo.lock',
    'shells/tauri-mobile/pnpm-lock.yaml',
    'shells/tauri-mobile/src-tauri/Cargo.lock',
  ]);
});

test('pnpm advisories count every severity while enforcing high/critical separately', () => {
  assert.deepEqual(auditCounts({ advisories: {} }), { total: 0, high: 0, critical: 0 });
  assert.deepEqual(auditCounts({ advisories: {
    one: { severity: 'moderate' }, two: { severity: 'high' }, three: { severity: 'critical' },
  } }), { total: 3, high: 1, critical: 1 });
});

test('audit errors and malformed advisory responses cannot look clean', () => {
  for (const report of [null, {}, { error: 'offline' }, { advisories: [] }, { advisories: { one: {} } }]) {
    assert.throws(() => auditCounts(report), /invalid advisory/);
  }
});

test('Cargo.lock reading keeps names, versions and versioned dependency entries', () => {
  const packages = parseCargoLock(lock(['a', '1.0.0', ['zip 4.6.1', 'zip 9.0.4 (registry+https://github.com/rust-lang/crates.io-index)', 'b']], ['b', '0.1.0']));
  assert.deepEqual(packages, [
    { name: 'a', version: '1.0.0', dependencies: [{ name: 'zip', version: '4.6.1' }, { name: 'zip', version: '9.0.4' }, { name: 'b' }] },
    { name: 'b', version: '0.1.0', dependencies: [] },
  ]);
  assert.equal(compareVersions('4.6.1', '9.0.0'), -1);
  assert.equal(compareVersions('9.0.0-pre3', '9.0.0'), -1);
  assert.equal(compareVersions('9.0.4', '9.0.0'), 1);
  assert.equal(compareVersions('2.14.1', '2.14.1'), 0);
  assert.equal(compareVersions('2.13.3', '2.14.1'), -1);
});

test('the zip advisory hold is scoped to the desktop Cargo root and still justified by its lockfile', () => {
  const inventory = loadInventory();
  const holding = inventory.roots.filter((root) => root.advisoryExceptions?.length);
  assert.deepEqual(holding.map((root) => root.id), ['tauri-desktop-cargo']);
  const [held] = holding;
  assert.ok(held);
  assert.deepEqual(held.advisoryExceptions?.flatMap((entry) => entry.advisories), ZIP_ADVISORIES);
  assert.doesNotThrow(() => validateAdvisoryExceptions(inventory));

  const desktop = cargoAuditArgs(held, 'Cargo.lock', false);
  assert.deepEqual(desktop, ['audit', '--file', 'Cargo.lock', ...ZIP_ADVISORIES.flatMap((id) => ['--ignore', id])]);
  for (const root of inventory.roots.filter((item) => item.ecosystem === 'cargo' && item.id !== 'tauri-desktop-cargo')) {
    assert.ok(!cargoAuditArgs(root, 'Cargo.lock', true).includes('--ignore'), `${root.id} must not inherit the desktop hold`);
  }
});

test('the advisory hold fails once it outlives the fix', () => {
  const problems = (text: string) => advisoryExceptionProblems(desktopRoot, parseCargoLock(text));
  assert.deepEqual(problems(heldLock), []);

  // zip moved to the fixed major.
  assert.match(problems(lock(app(), ['tauri-plugin-updater', '2.13.2', ['zip']], ['zip', '9.0.4'])).join('\n'), /zip resolves to 9\.0\.4, at or past the fix in 9\.0\.0\. Remove the exception/);
  // zip left the lockfile (the updater's zip feature switched off).
  assert.match(problems(lock(app(), ['tauri-plugin-updater', '2.13.2', ['tar']], ['tar', '0.4.46'])).join('\n'), /zip is no longer in .*Remove the exception/);
  // The updater release carrying the fix resolved, even before anyone touched zip.
  assert.match(problems(lock(app(), ['tauri-plugin-updater', '2.14.1', ['zip']], ['zip', '4.6.1'])).join('\n'), /tauri-plugin-updater 2\.14\.1 carries the upstream fix/);
  // The updater went away entirely.
  assert.match(problems(lock(['lolly-desktop', '1.1.1', ['other']], ['other', '1.0.0', ['zip']], ['zip', '4.6.1'])).join('\n'), /tauri-plugin-updater is no longer in/);
  // A second crate starts pulling the vulnerable copy, which the justification does not cover.
  assert.match(problems(lock(app('other'), ['tauri-plugin-updater', '2.13.2', ['zip']], ['other', '1.0.0', ['zip']], ['zip', '4.6.1'])).join('\n'), /other also pulls a vulnerable copy in/);
  // A pre-release of the fixed major is still vulnerable, so the hold stays valid.
  assert.deepEqual(problems(lock(app(), ['tauri-plugin-updater', '2.13.2', ['zip']], ['zip', '9.0.0-pre3'])), []);
  // Two copies: only the old one's parents matter, and a fixed copy elsewhere is fine.
  assert.deepEqual(problems(lock(app('other'), ['tauri-plugin-updater', '2.13.2', ['zip 4.6.1']], ['other', '1.0.0', ['zip 9.0.4']], ['zip', '4.6.1'], ['zip', '9.0.4'])), []);

  assert.throws(
    () => validateAdvisoryExceptions({ schemaVersion: 1, roots: [desktopRoot] }, () => lock(app(), ['tauri-plugin-updater', '2.14.1', ['zip']], ['zip', '9.0.4'])),
    /advisory exception gate:[\s\S]*zip resolves to 9\.0\.4[\s\S]*tauri-plugin-updater 2\.14\.1/,
  );
});

test('malformed or misplaced advisory exceptions are refused when the inventory loads', () => {
  const withException = (root: Partial<DependencyRoot>, exception: Partial<AdvisoryException>) =>
    parseInventory({ schemaVersion: 1, roots: [{ ...desktopRoot, ...root, advisoryExceptions: [exception as AdvisoryException] }] });
  assert.doesNotThrow(() => withException({}, zipException));
  assert.throws(() => withException({ ecosystem: 'npm' }, zipException), /cargo roots only/);
  assert.throws(() => withException({}, { ...zipException, advisories: [] }), /RUSTSEC-YYYY-NNNN/);
  assert.throws(() => withException({}, { ...zipException, advisories: ['GHSA-4684-h2q9-2vcp'] }), /RUSTSEC-YYYY-NNNN/);
  assert.throws(() => withException({}, { ...zipException, advisories: ['RUSTSEC-2026-0367', 'RUSTSEC-2026-0367'] }), /excepted twice/);
  assert.throws(() => withException({}, { ...zipException, justification: ' ' }), /missing justification/);
  assert.throws(() => withException({}, { ...zipException, viaFixedIn: '>=2.14.1' }), /plain x\.y\.z/);
  assert.throws(() => withException({}, { ...zipException, tracking: [] }), /tracking link/);
});
