/**
 * The prepared-file model behind every result surface (plans/236). DOM-free: the
 * deliverers are injected, so these pin the state machine itself - exact-byte
 * reuse, the busy guard, cancellation, failure, disposal and late completions.
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { DeliveryResult } from './delivery-result.ts';
import type { DeliveryOutcome } from './delivery-result.ts';

const tick = (): Promise<void> => new Promise(resolve => setTimeout(resolve, 0));
const file = (label = 'Export from 12:04'): { blob: Blob; filename: string; label: string } =>
  ({ blob: new Blob(['rendered once']), filename: 'poster.pdf', label });

test('a retry reuses the exact retained bytes and filename - nothing is regenerated', async () => {
  const seen: Array<{ blob: Blob; filename: string }> = [];
  const prepared = file();
  const result = new DeliveryResult(prepared, async (blob, filename) => { seen.push({ blob, filename }); return 'requested'; });
  assert.equal(result.state, 'ready');
  assert.equal(await result.retry(), 'requested');
  assert.equal(await result.retry(), 'requested');
  assert.equal(seen.length, 2);
  for (const call of seen) {
    assert.equal(call.blob, prepared.blob, 'the very same Blob object, never a rebuild');
    assert.equal(call.filename, 'poster.pdf');
  }
  assert.equal(result.state, 'requested', 'an anchor click is only ever a request');
});

test('only a closed write is Saved; a cancelled save leaves the file ready', async () => {
  let outcome: DeliveryOutcome = 'cancelled';
  const result = new DeliveryResult(file(), async () => 'requested', async () => outcome);
  assert.equal(await result.save(), 'cancelled');
  assert.equal(result.state, 'ready', 'cancelled is not a state - the file is simply still ready');
  assert.equal(result.lastOutcome, 'cancelled');
  assert.ok(result.file, 'the bytes survive a cancellation');
  outcome = 'saved';
  assert.equal(await result.save(), 'saved');
  assert.equal(result.state, 'saved');
});

test('a delivery failure keeps the bytes and a working retry; the error is the delivery error', async () => {
  let fail = true;
  const result = new DeliveryResult(file(), async () => { if (fail) throw new Error('disk write aborted'); return 'saved'; });
  assert.equal(await result.retry(), null);
  assert.equal(result.state, 'failed');
  assert.equal(result.error, 'disk write aborted');
  assert.ok(result.file, 'a failed save must not discard successfully generated bytes');
  fail = false;
  assert.equal(await result.retry(), 'saved');
  assert.equal(result.state, 'saved');
  assert.equal(result.error, null);
});

test('overlapping requests are refused while one is settling (double-click cannot start two writes)', async () => {
  let calls = 0;
  let release!: (o: DeliveryOutcome) => void;
  const result = new DeliveryResult(file(), () => { calls++; return new Promise<DeliveryOutcome>(resolve => { release = resolve; }); });
  const first = result.retry();
  assert.equal(result.busy, true);
  assert.equal(result.state, 'saving');
  assert.equal(await result.retry(), null, 'the second click is a no-op');
  assert.equal(await result.save(), null, 'and so is a different path while busy');
  assert.equal(calls, 1);
  release('saved');
  assert.equal(await first, 'saved');
  assert.equal(result.busy, false);
});

test('the picker path is invoked synchronously inside the call, before any await', () => {
  let invokedSynchronously = false;
  const result = new DeliveryResult(file(), async () => 'requested', () => { invokedSynchronously = true; return Promise.resolve('saved'); });
  void result.save();
  assert.equal(invokedSynchronously, true, 'the picker must be opened by the click that asked for it');
});

test('dispose releases the file, refuses further deliveries and drops a late completion', async () => {
  let release!: (o: DeliveryOutcome) => void;
  const result = new DeliveryResult(file(), () => new Promise<DeliveryOutcome>(resolve => { release = resolve; }));
  const events: string[] = [];
  result.subscribe(r => { events.push(r.state); });
  const inflight = result.retry();
  assert.deepEqual(events, ['saving']);
  result.dispose();
  assert.equal(result.disposed, true);
  assert.equal(result.file, null, 'the retained bytes are released');
  release('saved');
  assert.equal(await inflight, null, 'a completion after dispose returns nothing');
  assert.equal(result.state, 'saving', 'and repaints nothing - the surface has moved on');
  assert.deepEqual(events, ['saving'], 'listeners were cleared; no event for the stale completion');
  assert.equal(await result.retry(), null);
  assert.equal(await result.save(), null);
  await tick();
});

test('a hand-over made before the result existed is recorded honestly, and a delivery throw is a retryable failure', async () => {
  const result = new DeliveryResult(file(), async () => 'saved');
  result.recordOutcome('requested');
  assert.equal(result.state, 'requested', 'the first anchor click was only a request');
  result.recordOutcome('cancelled');
  assert.equal(result.state, 'ready');
  assert.equal(result.lastOutcome, 'cancelled');
  result.recordFailure('Download failed. Network gone.');
  assert.equal(result.state, 'failed');
  assert.equal(result.error, 'Download failed. Network gone.');
  assert.ok(result.file, 'the generated bytes survive a delivery failure');
  assert.equal(await result.retry(), 'saved', 'and the same bytes can still be handed over');
  result.dispose();
  result.recordOutcome('saved');
  result.recordFailure('late');
  assert.equal(result.state, 'saved', 'nothing is recorded after dispose');
});

test('subscribers hear every state change and can unsubscribe', async () => {
  const result = new DeliveryResult(file(), async () => 'saved');
  const heard: string[] = [];
  const off = result.subscribe(r => { heard.push(r.state); });
  await result.retry();
  assert.deepEqual(heard, ['saving', 'saved', 'saved'], 'saving, the settled state, then the busy flag clearing');
  off();
  await result.retry();
  assert.equal(heard.length, 3, 'nothing after unsubscribe');
});
