/** Makers whose AI output carries Google's SynthID mark. */
const SYNTHID_MAKERS = /google|gemini|imagen|veo|nano.?banana/i;

/**
 * The AI declaration as one row of the AI section: the declaration, the maker's
 * mark and name, and the credit as recorded. The section's heading states the
 * strength, so the row adds strength words only when its own differ. The AI
 * colour tints the glyph and two hairlines. The longer explanation and the note
 * about marks only a maker can read show at Evidence depth.
 */
export function aiRowHtml(input: AiRowInput, stated: VerifyStrength): string {
  const { origin } = input;
  if (!origin) return '';
  const copy = AI_COPY[origin.via][origin.kind];
  const likely = origin.via === 'fingerprint';
  // t() escapes its parameters and returns text ready for markup.
  const sub = likely ? t(copy.sub, { vendor: origin.vendor ?? '', products: origin.products ?? '' }) : esc(t(copy.sub));
  const note = SYNTHID_MAKERS.test(`${origin.credit ?? ''} ${input.makerHint}`)
    ? (input.audio
      ? t('Google’s AI models also stamp an invisible <strong>SynthID</strong> watermark into the audio signal itself, so this file very likely carries one - it survives re-encoding and metadata stripping.')
      : t('Google’s AI models also stamp an invisible <strong>SynthID</strong> watermark into the pixels themselves, so this file very likely carries one - it survives even when this label is stripped.'))
    : t('Large AI generators also typically stamp an invisible watermark into the pixels themselves (Google’s SynthID - also adopted by OpenAI - or Meta’s Video Seal), which survives metadata stripping.');
  const own = aiStrength(origin.via, input.verified);
  const chip = aiMakerChip(`${origin.vendor ?? ''} ${origin.credit ?? ''} ${input.makerHint}`, origin.via, input.verified, stated);
  return `<div class="vs-ai${likely ? ' is-likely' : ''}" role="alert" data-ai-via="${origin.via}">
      <span class="vs-ai-glyph" aria-hidden="true">${icon('aiSpark')}</span>
      <div class="vs-ai-copy">
        <p class="vs-ai-line"><strong>${esc(t(copy.title))}</strong>${chip}${chip || own === stated ? '' : strengthHtml(own)}</p>
        ${origin.credit ? `<p class="vs-ai-credit">“${esc(origin.credit)}”</p>` : ''}
        <p class="vs-ai-more" data-evidence-only hidden>${sub}</p>
        <p class="vs-ai-more" data-evidence-only hidden>${note}</p>
      </div>
    </div>`;
}

/**
 * A finding's evidence as rows: what was found, the value as recorded, and the
 * field it came from. `shown` is markup already on the page; a value it holds
 * is left out, so nothing is listed twice.
 */
export function evidenceRowsHtml(evidence: readonly VerifyEvidence[], stated: VerifyStrength, shown = ''): string {
  const rows = evidence.filter((e) => {
    const value = esc(e.value);
    return !(value.length >= 3 && shown.includes(value));
  }).slice(0, 24);
  if (!rows.length) return '';
  return `<dl class="vs-rows">${rows.map((e) => `<div><dt>${esc(t(e.label))}</dt><dd>${esc(e.value)}</dd><dd class="vs-source">${esc(e.source)}${e.strength === stated ? '' : strengthHtml(e.strength)}</dd></div>`).join('')}</dl>`;
}

/** What Verify can still check on one file's pixels, when asked. */
export interface PixelChecks {
  fileIndex: number;
  /** A browser decode can read this file's pixels. */
  scannable: boolean;
  /** Offer the search for a cropped or resized Lolly Imprint. */
  rescan: boolean;
}

/**
 * The checks a reader starts by hand, each one row: the control, then what the
 * check costs. The watermark row stays hidden until the view offers the scan
 * (`offerDeepScan`), because it asks for a download and one consent covers every
 * file in the batch.
 */
export function pixelCheckRowsHtml(checks: PixelChecks): string {
  if (!checks.scannable) return '';
  const i = checks.fileIndex;
  const scan = `<div class="vs-action" data-deepscan-banner>
      <button type="button" class="btn" data-deep-scan-enable>${icon('imprint')}<span>${t('Scan for invisible watermarks')}</span></button>
      <p class="vs-action-note"><span data-deepscan-banner-msg>${t('Adobe TrustMark and Meta Content Seal. Downloads a detector once (~90 MB). Nothing is uploaded.')}</span></p>
      <div class="valid-deepscan-progress" data-deepscan-progress role="progressbar" aria-label="${esc(t('Downloading the watermark detector'))}" hidden>
        <div class="valid-deepscan-progress-fill" data-deepscan-progress-fill></div>
      </div>
    </div>`;
  const rescan = checks.rescan ? `<div class="vs-action" data-imprint-rescan-block="${i}">
      <button type="button" class="btn" data-imprint-rescan="${i}">${icon('search')}<span>${t('Search for a resized Imprint')}</span></button>
      <p class="vs-action-note">${t('Search for a Lolly Imprint after cropping or resizing. Runs on this device.')}</p>
      <div class="vs-action-result" data-imprint-rescan-result="${i}"></div>
    </div>` : '';
  return scan + rescan;
}

/**
 * Show or withdraw the watermark scan on every report under `root`. 'busy'
 * leaves only the row that was pressed, which then carries the progress.
 * 'offer' puts every row back the way a reader first saw the control: the
 * button ready and no progress bar.
 */
export function offerDeepScan(root: HTMLElement, state: 'offer' | 'busy' | 'none', pressed?: HTMLElement | null): void {
  if (state === 'none') delete root.dataset.deepscanOffer;
  else root.dataset.deepscanOffer = state;
  for (const row of root.querySelectorAll<HTMLElement>('[data-deepscan-banner]')) {
    row.classList.toggle('is-running', state === 'busy' && row === pressed);
    if (state !== 'offer') continue;
    row.querySelector('[data-deepscan-progress]')?.setAttribute('hidden', '');
    const button = row.querySelector<HTMLButtonElement>('[data-deep-scan-enable]');
    if (button) button.disabled = false;
  }
}
